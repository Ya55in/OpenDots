import { Component, type ReactNode } from 'react';

// Outside the lazy-loaded module so chunk-load failures also preserve the chat.
export class OpenUIBoundary extends Component<
  { children: ReactNode; fallback: ReactNode },
  { failed: boolean }
> {
  state = { failed: false };
  static getDerivedStateFromError() {
    return { failed: true };
  }
  render() {
    return this.state.failed ? this.props.fallback : this.props.children;
  }
}
